USE DB_SP_SP;
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

BEGIN TRAN;

WITH ranked AS (
  SELECT ROW_NUMBER() OVER (
           PARTITION BY FUNCTION_ID
           ORDER BY CASE WHEN LTRIM(RTRIM(PLANT_CODE)) = N'*' THEN 0 ELSE 1 END, ID
         ) AS rn
    FROM dbo.TB_M_ETD_EMAIL_CONTENT
)
DELETE FROM ranked WHERE rn > 1;
PRINT CONCAT('duplicate template rows deleted: ', @@ROWCOUNT);

IF COLUMNPROPERTY(OBJECT_ID('dbo.TB_M_ETD_EMAIL_CONTENT'), 'PLANT_CODE', 'AllowsNull') = 0
BEGIN
  IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_ETD_EMAIL_CONTENT_KEY'
               AND object_id = OBJECT_ID('dbo.TB_M_ETD_EMAIL_CONTENT'))
    DROP INDEX IX_ETD_EMAIL_CONTENT_KEY ON dbo.TB_M_ETD_EMAIL_CONTENT;
  ALTER TABLE dbo.TB_M_ETD_EMAIL_CONTENT ALTER COLUMN PLANT_CODE NVARCHAR(50) NULL;
  PRINT 'PLANT_CODE is now nullable';
END

COMMIT;
GO

BEGIN TRAN;

UPDATE dbo.TB_M_ETD_EMAIL_CONTENT SET PLANT_CODE = NULL WHERE PLANT_CODE IS NOT NULL;
PRINT CONCAT('PLANT_CODE cleared on rows: ', @@ROWCOUNT);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_ETD_EMAIL_CONTENT_KEY'
                 AND object_id = OBJECT_ID('dbo.TB_M_ETD_EMAIL_CONTENT'))
BEGIN
  CREATE UNIQUE INDEX IX_ETD_EMAIL_CONTENT_KEY ON dbo.TB_M_ETD_EMAIL_CONTENT (FUNCTION_ID, PLANT_CODE);
  PRINT 'unique index IX_ETD_EMAIL_CONTENT_KEY created';
END

COMMIT;
GO

SELECT
  (SELECT COUNT(*) FROM (SELECT FUNCTION_ID FROM dbo.TB_M_ETD_EMAIL_CONTENT
                          GROUP BY FUNCTION_ID HAVING COUNT(*) > 1) d) AS functions_with_duplicates,
  COLUMNPROPERTY(OBJECT_ID('dbo.TB_M_ETD_EMAIL_CONTENT'), 'PLANT_CODE', 'AllowsNull') AS plant_code_nullable,
  (SELECT COUNT(*) FROM sys.indexes WHERE name = 'IX_ETD_EMAIL_CONTENT_KEY'
     AND object_id = OBJECT_ID('dbo.TB_M_ETD_EMAIL_CONTENT') AND is_unique = 1) AS unique_index_present,
  (SELECT COUNT(*) FROM dbo.TB_M_ETD_EMAIL_CONTENT) AS template_rows;
GO
