USE DB_SP_PRO;

IF COL_LENGTH('dbo.TB_R_PO_DDD_N', 'PO_NO') IS NULL
  ALTER TABLE dbo.TB_R_PO_DDD_N ADD PO_NO nvarchar(20) NULL;
IF COL_LENGTH('dbo.TB_R_PO_DDD_N', 'PO_ITEM_NO') IS NULL
  ALTER TABLE dbo.TB_R_PO_DDD_N ADD PO_ITEM_NO nvarchar(10) NULL;
IF COL_LENGTH('dbo.TB_R_PO_DDD_N', 'DELIVERY_DATE') IS NULL
  ALTER TABLE dbo.TB_R_PO_DDD_N ADD DELIVERY_DATE date NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.TB_R_PO_DDD_N') AND name = 'IX_TB_R_PO_DDD_N_PO_NO_ITEM')
  CREATE NONCLUSTERED INDEX IX_TB_R_PO_DDD_N_PO_NO_ITEM ON dbo.TB_R_PO_DDD_N (PO_NO, PO_ITEM_NO) INCLUDE (DELIVERY_DATE);
GO
